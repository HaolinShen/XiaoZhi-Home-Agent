"""说明书检索的分词层：jieba 词典分词 + 错误码整体保留。

为什么换掉字符 bigram
--------------------
012 及之前的分词是"把所有汉字抽出来拼成一串，再滑窗取相邻两字"。它的代价有三处，
前两处会掩盖失败，第三处直接堵住了 BM25：

- **伪词会意外匹配。** "客厅空调显示"切出「厅空」「调显」这类不存在的词。它们在
  查询侧和文档侧规则一致，所以偶尔真能对上，于是一次本该暴露的召回失败被掩盖成
  "分数低但有命中"。
- **跨边界。** 非汉字字符（空格、标点、错误码）被整体删掉之后才拼接，
  "显示 E3 是什么"会切出跨过 E3 的「示是」。
- **丢词频。** 旧实现返回 `set`，一个词出现 10 次和 1 次同权。BM25 的 TF 项
  在建集合的那一步就已经没了，所以旧打分只能是"覆盖率"。

jieba 用词典切分，前两条不存在；这里返回 `list` 而不是 `set`，把词频交给 BM25。

用 cut_for_search，并且关掉 HMM
-----------------------------
`cut_for_search` 是搜索引擎模式，长词会再切出短词（"排水泵" → 排水 / 水泵 / 排水泵）。
查询侧和文档侧**都**用它，是刻意的对称：如果文档切成「排水」「泵」而查询切成
「排水泵」，这一项就完全对不上，而且失败得很安静。多切出来的短词会抬高文档长度，
BM25 的长度归一化本来就是干这件事的。

`HMM=False` 关掉新词发现，这是实测逼出来的。默认开着 HMM 时：

    jieba.cut_for_search("卧室灯不太亮了")  →  卧室 / 灯不太亮 / 了

「灯不太亮」是 HMM 凭概率粘出来的词，**任何说明书里都不存在**。于是 BM25 只剩
「卧室」可用，而「卧室」恰好出现在「清洁周期」那节（"普通卧室环境建议…"）、
不出现在正确的「亮度明显偏低」里——BM25 因此给错误小节 4.84 分、正确小节 0 分。

关掉之后变成 卧室 / 灯 / 不 / 太 / 亮 / 了，「亮」能对上「亮度」。

代价是文档侧的技术词会被拆散（换能片 → 换/能/片，热释电 → 热/释/电）。
这个代价可以接受，因为它是**对称**的：用户问「换能片」时查询也这样拆，
仍然匹配得上，只是单字 IDF 低、信号弱一些——损失的是精度。
而 HMM 粘连损失的是召回，直接归零。**非对称粘连严格劣于对称拆分。**
（想把技术词的精度找回来，下一步是给 jieba 挂一份领域词典；
本轮不做，因为那会多出一处要和语料同步的声明。）
"""

from __future__ import annotations

import logging
import re

import jieba

# jieba 首次分词会往 stderr 打 "Building prefix dict..."，CLI 里会突然冒出来。
jieba.setLogLevel(logging.WARNING)

# 错误码的唯一正则。型号硬过滤（base.py）和"带错误码的查询永不重写"（rag.py）
# 都用这一份。012 时代它在两个文件里各写了一遍，靠一句注释"保持一致"约束——
# 改一处漏一处不报错，只会让两处判断悄悄分叉。
#
# 边界用 ASCII 前后向断言而不是 `\b`：Unicode 模式下汉字也算 `\w`，
# 所以 `\bE3\b` 在"显示E3是什么"里**匹配不到**（示与 E 之间没有 \b）。
# 旧实现只在用户恰好打了空格时才认得出错误码，不打空格就静默走成普通口语查询。
# 换成 `(?<![a-z0-9])` 后，汉字、标点都算边界，型号串（ac2024）仍然不会被误当成码。
CODE_PATTERN = re.compile(r"(?<![a-z0-9])(?:[a-z]\d+|\d{3,})(?![a-z0-9])")

# 只收纯功能词，刻意保持得很短。
#
# 为什么还需要停用词表——BM25 里对不上的查询词贡献 0 分，本来不该有影响：
# 问题出在**对得上**的那些。"是""在""有"这类词在说明书里真的会出现
# （"E3 表示……"），IDF 只能把它们压低、压不到 0。于是每个小节都会拿到一份
# 均匀的噪声底分，而本模块的下游是**绝对分数守门**（rag.py 的三档下限）——
# 抬高噪声底分等于让垃圾看起来也有分。所以这里只删那些"出现与否都不携带检索信号"
# 的词，语义词一律留给 IDF 处理。
_STOPWORDS = frozenset(
    """
    的 了 着 过 地 得 之 是 在 有 和 与 或 及 就 都 也 还 又 而 但 却
    很 太 更 最 挺 比较 有点 一点 一些 一下 稍微
    吗 呢 吧 啊 呀 哦 嘛 么
    我 你 他 她 它 我们 你们 他们 自己
    这 那 这个 那个 这些 那些 什么 怎么 怎样 如何 为什么 哪个 哪些
    可以 能 会 要 想 需要 应该 请 帮 让 给 把 被 对 从 到 向 用
    上 下 里 外 前 后 时 时候 现在 一直 总是 老是 突然 好像 似乎 感觉
    问题 情况 办 怎么办 回事
    """.split()
)


def tokenize(text: str) -> list[str]:
    """把一段中文（可含英文与错误码）切成检索用的 token 列表。

    错误码先被整体摘出来当独立 token，再把它从原文里挖掉，剩下的部分才交给 jieba。
    两步都是必要的：

    - 先摘，否则 "E3" 会被切成「e」和「3」，而单字母在下面会被丢掉，
      结果是**错误码在检索里彻底消失**，偏偏它是这套语料里最精确的键。
    - 再挖掉，否则同一个码会被计两次（摘出来一次、jieba 又切出一次），
      TF 凭空翻倍——那是巧合而不是设计。挖成空格同时也断开了
      "显示E3是什么"这种跨码的伪词。
    """
    lowered = text.lower()

    codes = CODE_PATTERN.findall(lowered)
    tokens: list[str] = list(codes)

    for piece in jieba.cut_for_search(CODE_PATTERN.sub(" ", lowered), HMM=False):
        piece = piece.strip()
        if not piece or piece in _STOPWORDS:
            continue
        if piece.isascii():
            # 单个字母/数字是噪声（"a"、"3"）；真正有意义的短 ASCII 串
            # 已经作为错误码摘走了。下划线与连字符保留，它们是标识符的一部分。
            if len(piece) < 2 or not any(char.isalnum() for char in piece):
                continue
            tokens.append(piece)
            continue
        # 中日韩字符：单字保留（"冷""热""霜"在短查询里是主要信号），
        # 常见单字的权重由 IDF 压制，不在这里靠长度硬砍。
        if any(char.isalnum() for char in piece):
            tokens.append(piece)

    return tokens


def extract_codes(text: str) -> set[str]:
    """摘出文本里的全部错误码，小写。型号硬过滤前的精确键就是它。"""
    return set(CODE_PATTERN.findall(text.lower()))
